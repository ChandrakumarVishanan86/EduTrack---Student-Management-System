-- =====================================================================
--  Student Management System  -  database.sql
--  Import in phpMyAdmin:  Import tab -> choose this file -> Go
--  (the script creates the database `student_management` itself)
--
--  Default logins (change after first sign-in!)
--     admin     / admin123       -> Administrator
--     lecturer1 / lecturer123    -> Lecturer
--     lecturer2 / lecturer123    -> Lecturer
--     S2024001  / student123     -> Student  (any reg_no works the same)
-- =====================================================================

CREATE DATABASE IF NOT EXISTS `student_management`
  DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `student_management`;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS `marks`;
DROP TABLE IF EXISTS `attendance`;
DROP TABLE IF EXISTS `enrollments`;
DROP TABLE IF EXISTS `courses`;
DROP TABLE IF EXISTS `users`;
DROP TABLE IF EXISTS `students`;
SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------------------------------------------------
-- students
-- ---------------------------------------------------------------------
CREATE TABLE `students` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `reg_no`      VARCHAR(30)  NOT NULL,
  `first_name`  VARCHAR(60)  NOT NULL,
  `last_name`   VARCHAR(60)  NOT NULL,
  `email`       VARCHAR(120) NOT NULL,
  `phone`       VARCHAR(25)  DEFAULT NULL,
  `dob`         DATE         DEFAULT NULL,
  `gender`      ENUM('Male','Female','Other') NOT NULL DEFAULT 'Male',
  `address`     VARCHAR(255) DEFAULT NULL,
  `department`  VARCHAR(80)  NOT NULL,
  `batch_year`  SMALLINT UNSIGNED NOT NULL,
  `status`      ENUM('Active','Inactive','Graduated') NOT NULL DEFAULT 'Active',
  `created_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_students_reg_no` (`reg_no`),
  UNIQUE KEY `uq_students_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- users  (admin / lecturer / student logins)
-- ---------------------------------------------------------------------
CREATE TABLE `users` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `username`    VARCHAR(50)  NOT NULL,
  `password`    VARCHAR(255) NOT NULL,              -- password_hash() output
  `full_name`   VARCHAR(120) NOT NULL,
  `email`       VARCHAR(120) DEFAULT NULL,
  `role`        ENUM('admin','lecturer','student') NOT NULL,
  `student_id`  INT UNSIGNED DEFAULT NULL,          -- set only for role = student
  `is_active`   TINYINT(1) NOT NULL DEFAULT 1,
  `last_login`  DATETIME DEFAULT NULL,
  `created_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_users_username` (`username`),
  KEY `idx_users_role` (`role`),
  CONSTRAINT `fk_users_student` FOREIGN KEY (`student_id`)
    REFERENCES `students` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- courses
-- ---------------------------------------------------------------------
CREATE TABLE `courses` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `code`        VARCHAR(20)  NOT NULL,
  `name`        VARCHAR(150) NOT NULL,
  `credits`     TINYINT UNSIGNED NOT NULL DEFAULT 3,
  `semester`    TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `lecturer_id` INT UNSIGNED DEFAULT NULL,
  `created_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_courses_code` (`code`),
  CONSTRAINT `fk_courses_lecturer` FOREIGN KEY (`lecturer_id`)
    REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- enrollments  (student <-> course)
-- ---------------------------------------------------------------------
CREATE TABLE `enrollments` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `student_id`  INT UNSIGNED NOT NULL,
  `course_id`   INT UNSIGNED NOT NULL,
  `enrolled_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_enroll` (`student_id`,`course_id`),
  KEY `idx_enroll_course` (`course_id`),
  CONSTRAINT `fk_enroll_student` FOREIGN KEY (`student_id`)
    REFERENCES `students` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_enroll_course` FOREIGN KEY (`course_id`)
    REFERENCES `courses` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- attendance  (one row per student / course / day)
-- ---------------------------------------------------------------------
CREATE TABLE `attendance` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `student_id`  INT UNSIGNED NOT NULL,
  `course_id`   INT UNSIGNED NOT NULL,
  `att_date`    DATE NOT NULL,
  `status`      ENUM('present','absent') NOT NULL DEFAULT 'present',
  `marked_by`   INT UNSIGNED DEFAULT NULL,
  `updated_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_att` (`student_id`,`course_id`,`att_date`),
  KEY `idx_att_course_date` (`course_id`,`att_date`),
  CONSTRAINT `fk_att_student` FOREIGN KEY (`student_id`)
    REFERENCES `students` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_att_course` FOREIGN KEY (`course_id`)
    REFERENCES `courses` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_att_user` FOREIGN KEY (`marked_by`)
    REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- marks  (one final mark per student / course, 0-100)
-- ---------------------------------------------------------------------
CREATE TABLE `marks` (
  `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `student_id`  INT UNSIGNED NOT NULL,
  `course_id`   INT UNSIGNED NOT NULL,
  `marks`       DECIMAL(5,2) NOT NULL,
  `grade`       VARCHAR(3)   NOT NULL,
  `grade_point` DECIMAL(3,2) NOT NULL,               -- marks / 25  (0.00 - 4.00)
  `entered_by`  INT UNSIGNED DEFAULT NULL,
  `updated_at`  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_marks` (`student_id`,`course_id`),
  KEY `idx_marks_course` (`course_id`),
  CONSTRAINT `chk_marks_range` CHECK (`marks` >= 0 AND `marks` <= 100),
  CONSTRAINT `fk_marks_student` FOREIGN KEY (`student_id`)
    REFERENCES `students` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_marks_course` FOREIGN KEY (`course_id`)
    REFERENCES `courses` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_marks_user` FOREIGN KEY (`entered_by`)
    REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

